import { chromium } from "playwright";
import http from "http"; import fs from "fs"; import path from "path";
const root = path.resolve(new URL("../www", import.meta.url).pathname);
const types = { ".html":"text/html", ".js":"text/javascript", ".mjs":"text/javascript", ".css":"text/css", ".png":"image/png", ".woff2":"font/woff2", ".json":"application/json", ".webmanifest":"application/manifest+json", ".wasm":"application/wasm" };
const srv = http.createServer((q, r) => { let p = path.join(root, decodeURIComponent(q.url.split("?")[0])); if (p.endsWith("/")) p += "index.html";
  fs.readFile(p, (e, d) => { if (e) { r.writeHead(404); r.end(); } else { r.writeHead(200, { "content-type": types[path.extname(p)] || "application/octet-stream" }); r.end(d); } }); }).listen(0);
const port = srv.address().port, base = `http://localhost:${port}/`;
fs.mkdirSync("screenshots", { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, serviceWorkers: "block" });
const pg = await ctx.newPage();
const errs = []; pg.on("pageerror", (e) => errs.push(e.message)); pg.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
const lang = process.argv[2] || "en";
await pg.addInitScript((l) => { try { localStorage.setItem("oru.lang", l); } catch (e) {} }, lang);
await pg.goto(base); await pg.waitForTimeout(600);
const shot = async (n) => { await pg.waitForTimeout(250); await pg.screenshot({ path: `screenshots/${lang}-${n}.png` }); };
await shot("1-splash");
await pg.click(".splash-hit"); await shot("2-home");
await pg.click(".home-tile >> nth=0"); await shot("3-report");
await pg.click(".issue >> nth=0"); await pg.click(".areakey >> nth=0");
await pg.fill("#f_address", "12 Main Road, Chrompet"); await pg.fill("#f_landmark", "near the temple"); await pg.fill("#f_name", "Arjun"); await pg.fill("#f_phone", "9876543210");
await shot("3b-report-filled");
await pg.click(".key-red"); await shot("4-letter");
await pg.goto(base + "?x=" + Math.random() + "#crop"); await pg.waitForTimeout(500);
await pg.click(".issue >> nth=0"); await shot("5-crop");
await pg.click(".areakey >> nth=0"); await shot("6-crop-result");
await pg.goto(base + "?x=" + Math.random() + "#helper"); await pg.waitForTimeout(500); await shot("7-helper");
await pg.goto(base + "?x=" + Math.random() + "#history"); await pg.waitForTimeout(500); await shot("8-history");
await pg.goto(base + "?x=" + Math.random() + "#emergency"); await pg.waitForTimeout(500); await shot("9-emergency");
console.log("errors:", errs);
await b.close(); srv.close();
