def main():
    strings = literal(ROOT / "oru" / "i18n.py", "STRINGS")
    strings.update(MOBILE)
    rules = literal(ROOT / "oru" / "labels.py", "RULES")
    data = ROOT / "oru" / "data"
    out = {
        "STRINGS": {k: {"ta": v[0], "en": v[1]} for k, v in strings.items()},
        "ISSUES": json.loads((data / "issues.json").read_text("utf-8"))["issues"],
        "DEPTS": json.loads((data / "departments.json").read_text("utf-8")),
        "REMEDIES": json.loads((data / "remedies.json").read_text("utf-8")),
        "LABEL_RULES": [{"crop": c, "must": list(m), "id": i} for c, m, i in rules],
    }
    text = "// GENERATED by tools/gen_mobile_data.py. Do not edit by hand.\n"
    for k, v in out.items():
        text += f"export const {k} = {json.dumps(v, ensure_ascii=False, indent=1)};\n"
    dest = ROOT / "mobile" / "www" / "js" / "data.js"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, "utf-8")
    print(f"wrote {dest} ({len(text) // 1024} KB, {len(strings)} strings)")


if __name__ == "__main__":
    main()
