"""Builds mobile/www/js/data.js from the SAME files the Linux app uses, so both apps always agree:
   oru/i18n.py (STRINGS), oru/labels.py (RULES), oru/data/*.json.
Run:  python tools/gen_mobile_data.py     (re-run after editing any of those files)"""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def literal(path: Path, name: str):
    tree = ast.parse(path.read_text("utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == name:
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in {path}")


